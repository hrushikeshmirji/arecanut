def generate_fig_2_2():
    print("[2/14] Generating Fig. 2.2: Number of images in each class...")
    classes = [
        "bud_borer", "fruit_rot", "healthy_leaf", "healthy_nut",
        "healthy_trunk", "non_areca", "stem_bleeding", "stem_cracking", "yellow_leaf"
    ]
    display_names = [
        "Bud Borer", "Fruit Rot (Koleroga)", "Healthy Leaf", "Healthy Nut",
        "Healthy Trunk", "Non-Areca (OOD)", "Stem Bleeding", "Stem Cracking", "Yellow Leaf Disease"
    ]

    train_counts = []
    val_counts = []
    for c in classes:
        train_counts.append(len(list((TRAIN_DIR / c).glob("*.*"))))
        val_counts.append(len(list((VAL_DIR / c).glob("*.*"))))

    train_counts = np.array(train_counts)
    val_counts = np.array(val_counts)
    total_counts = train_counts + val_counts

    fig, ax = plt.subplots(figsize=(11, 6.5), dpi=300)
    y_pos = np.arange(len(classes))
    bar_height = 0.55

    # Horizontal stacked bars
    p1 = ax.barh(y_pos, train_counts, bar_height, label="Training Split (80%)", color="#059669", edgecolor="#047857")
    p2 = ax.barh(y_pos, val_counts, bar_height, left=train_counts, label="Validation Split (20%)", color="#0284c7", edgecolor="#0369a1")

    # Annotate total counts on each bar
    for idx, (t, v, tot) in enumerate(zip(train_counts, val_counts, total_counts)):
        ax.text(tot + 2, idx, f"{tot} (Train: {t}, Val: {v})", va="center", fontsize=8.5, fontweight="bold", color="#1e293b")

    ax.set_yticks(y_pos)
    ax.set_yticklabels(display_names, fontsize=9.5, fontweight="medium")
    ax.invert_yaxis()  # Top-down order
    ax.set_xlabel("Number of Images", fontsize=10.5, fontweight="bold", labelpad=8)
    ax.set_xlim(0, max(total_counts) + 38)
    ax.grid(axis="x", linestyle="--", alpha=0.5)

    ax.set_title("Dataset Distribution Across Canonical Arecanut Classes & Negative OOD Class",
                 fontsize=12, fontweight="bold", pad=12, color="#0f172a")

    total_all = sum(total_counts)
    total_train = sum(train_counts)
    total_val = sum(val_counts)
    ax.legend(loc="lower right", frameon=True, framealpha=0.95, fontsize=9.5)

    # Inset textbox with dataset summary
    summary_text = f"Dataset Summary:\n• Total Classes: 9\n• Total Images: {total_all}\n• Train Split: {total_train} (79.6%)\n• Validation Split: {total_val} (20.4%)"
    ax.text(0.72, 0.40, summary_text, transform=ax.transAxes, fontsize=9,
            verticalalignment="top", bbox=dict(boxstyle="round,pad=0.5", facecolor="#f8fafc", edgecolor="#cbd5e1", lw=1.2))

    fig.text(0.5, 0.01, "Figure 2.2: Distribution of verified, noise-filtered specimen images across all nine canonical classes.",
             ha="center", fontsize=9, fontstyle="italic", color="#475569")

    plt.tight_layout()
    out_path = OUTPUT_DIR / "Fig_2_2_number_of_images_in_each_class.png"
    plt.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close(fig)
